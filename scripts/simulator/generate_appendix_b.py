# Gamewith特性一覧に定義があるが、DBに保持ポケモンが現れない特性の補完用（現在は空。
# メガ表を完全化したため不要だが、将来 DB 反映前の新特性を母集合に含める受け皿として残す）。
EXTRA_DEFINED = []


def implemented_abilities(all_names) -> set:
    """simulator/*.py のコード中に特性名が文字列リテラルとして現れる＝実装/参照ありとみなす。
    辞書キー・リスト要素・比較いずれの形でも検出する（コメント行は除外）。"""
    src = ""
    for f in glob.glob(str(ROOT / "simulator" / "*.py")):
        if f.endswith("generate_appendix_b.py"):
            continue
        for line in open(f, encoding="utf-8"):
            if line.lstrip().startswith("#"):
                continue  # コメント行は除外
            src += line
    return {n for n in all_names if f'"{n}"' in src or f"'{n}'" in src}


def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    base = [r[0] for r in cur.execute(
        "SELECT DISTINCT ability FROM pokemon_abilities ORDER BY ability").fetchall()]
    # メガシンカ専用特性も母集合に含める（pokemon_mega_stats.ability）。表記揺れを正規化。
    NORM = {"かたいつめ": "かたいツメ"}
    mega = [NORM.get(r[0], r[0]) for r in cur.execute(
        "SELECT DISTINCT ability FROM pokemon_mega_stats "
        "WHERE ability IS NOT NULL AND ability != ''").fetchall()]
    seen, abilities = set(), []
    for a in base + mega + EXTRA_DEFINED:
        if a not in seen:
            seen.add(a); abilities.append(a)
    abilities.sort()

    impl = implemented_abilities(abilities)

    cur.execute("""CREATE TABLE IF NOT EXISTS ability_master (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name_jp TEXT NOT NULL UNIQUE,
        effect_text TEXT,
        implemented INTEGER NOT NULL DEFAULT 0
    )""")
    for name in abilities:
        eff = EFFECTS.get(name, "")
        cur.execute("""INSERT INTO ability_master (name_jp, effect_text, implemented)
            VALUES (?, ?, ?)
            ON CONFLICT(name_jp) DO UPDATE SET effect_text=excluded.effect_text,
                                               implemented=excluded.implemented""",
                    (name, eff, 1 if name in impl else 0))
    conn.commit()

    n_impl = sum(1 for a in abilities if a in impl)
    n_eff = sum(1 for a in abilities if EFFECTS.get(a))
    rows = []
    for name in abilities:
        eff = EFFECTS.get(name, "")
        mark_impl = "✅" if name in impl else "—"
        mark_eff = eff if eff else "（効果未取得・要確認）"
        rows.append(f"| {name} | {mark_impl} | {mark_eff} |")

    out = f"""# 付録B. 特性（とくせい）一覧

> **ソース**: 環境出現特性は `pokemon_abilities`（{len(abilities)}種）。効果文は gamewith ポケモンチャンピオンズ特性一覧を参照（あ〜ゆ範囲を収録済み）。
> **実装**: ✅ = `simulator/*.py` で効果ディスパッチを確認（実装済み {n_impl}/{len(abilities)}）。— = 未実装または未確認。
> **効果未取得・要確認**: 効果文をまだ確実に取得できていない特性（{len(abilities) - n_eff}種）。仕様確定が必要。
> **注意**: 本表は「環境に出現する特性」の管理表。effect_text を仕様の真実源とし、move_master と同様に今後テスト生成・監査の基盤にする。

| 特性 | 実装 | 効果（仕様） |
|------|------|------|
{chr(10).join(rows)}
"""
    (ROOT / "simulator" / "appendix_b.md").write_text(out, encoding="utf-8")
    conn.close()
    print(f"特性総数: {len(abilities)} / 実装確認: {n_impl} / 効果収録: {n_eff} / 要確認: {len(abilities) - n_eff}")
    print(f"出力: {ROOT / 'simulator' / 'appendix_b.md'}")


if __name__ == "__main__":
    main()
