def type_effectiveness(types: list) -> dict:
    """与えられたタイプリスト（1〜2種）に対する全タイプの効果倍率を返す"""
    result = {}
    for atk in ALL_TYPES:
        mult = 1.0
        for t in types:
            mult *= DEFENSE.get(t, {}).get(atk, 1.0)
        if mult != 1.0:
            result[atk] = mult
    return result

