def latest(conn, table, pokemon, field=None):
    if field is None:
        field = f"season='{SEASON}' AND rule='single'"
    row = conn.execute(
        f"SELECT MAX(crawled_date) FROM {table} WHERE {field} AND pokemon=?", (pokemon,)
    ).fetchone()
    return row[0] if row else None


def query_db(conn, table, pokemon, col, alias=None):
    date = latest(conn, table, pokemon)
    if not date:
        return []
    rows = conn.execute(
        f"SELECT * FROM {table} WHERE season='{SEASON}' AND rule='single' AND pokemon=? AND crawled_date=? ORDER BY usage_rate DESC LIMIT 10",
        (pokemon, date)
    ).fetchall()
    return rows


