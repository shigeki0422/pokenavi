def main():
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row

    inserted = 0
    skipped = 0
    for row in CHAMPIONS_MEGAS:
        (mega_name, base_name, stone, dex, t1, t2,
         hp, atk, dfs, spatk, spdef, spd, ability) = row

        exists = con.execute(
            "SELECT id FROM pokemon_mega_stats WHERE mega_stone=?", (stone,)
        ).fetchone()
        if exists:
            print(f"SKIP (already exists): {mega_name}")
            skipped += 1
            continue

        con.execute("""
            INSERT INTO pokemon_mega_stats
              (mega_name_jp, base_pokemon_jp, mega_stone, base_dex,
               pokeapi_name, type1, type2, hp, attack, defense,
               sp_attack, sp_defense, speed, ability)
            VALUES (?,?,?,?,NULL,?,?,?,?,?,?,?,?,?)
        """, (mega_name, base_name, stone, dex, t1, t2,
              hp, atk, dfs, spatk, spdef, spd, ability))
        bst = hp + atk + dfs + spatk + spdef + spd
        print(f"INSERT: {mega_name} ({t1}/{t2 or '-'}) BST={bst} [{ability}]")
        inserted += 1

    # gamewith由来のメガ重さ（kg）。種族値変化に伴い重さも変わる（ヘビーボンバー等に影響）
    MEGA_WEIGHTS = {"メガオーダイル": 108.8, "メガメガニウム": 201.0, "メガニャオニクス": 10.1}
    try:
        con.execute("ALTER TABLE pokemon_mega_stats ADD COLUMN weight_kg REAL")
    except sqlite3.OperationalError:
        pass
    for mn, w in MEGA_WEIGHTS.items():
        con.execute("UPDATE pokemon_mega_stats SET weight_kg=? WHERE mega_name_jp=?", (w, mn))

    con.commit()
    con.close()
    print(f"\n完了: {inserted}件INSERT, {skipped}件スキップ")


if __name__ == "__main__":
    import os, sys
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    main()
